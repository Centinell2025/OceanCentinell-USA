import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const source = fs.readFileSync(new URL("../app.js", import.meta.url), "utf8");
const slice = source.slice(source.indexOf('const KEY='), source.indexOf('function load()'));
if (!slice.includes('function validData')) throw new Error("Validator not found");
const context = vm.createContext({Date,Set,String,Array,Object,Number});
const validate = vm.runInContext(slice+"\nvalidData",context);
const sample = {vessels:[{id:"valid-1",name:"Boat",identifier:"USA-1",status:"Operational"}],assets:[],incidents:[],maintenance:[]};
const copy = x => JSON.parse(JSON.stringify(x));
test("accepts a correct local dataset",()=>assert.equal(validate(sample),true));
test("rejects missing required fields",()=>{const d=copy(sample);delete d.vessels[0].name;assert.equal(validate(d),false)});
test("rejects unsanctioned status",()=>{const d=copy(sample);d.vessels[0].status="Definitely safe";assert.equal(validate(d),false)});
test("rejects prototype object values in record fields",()=>{const d=copy(sample);d.vessels[0].name={injected:true};assert.equal(validate(d),false)});
test("rejects duplicate IDs across collections",()=>{const d=copy(sample);d.assets=[{id:"valid-1",name:"Radar",category:"Electronics",status:"Operational"}];assert.equal(validate(d),false)});
test("rejects impossible dates",()=>{const d=copy(sample);d.maintenance=[{id:"maint-2",title:"Check",due:"2026-02-30",status:"Planned"}];assert.equal(validate(d),false)});
test("rejects invalid record count",()=>{const d=copy(sample);d.vessels=Array.from({length:1001},(_,i)=>({...sample.vessels[0],id:"id-"+i}));assert.equal(validate(d),false)});
test("rejects extremely long input",()=>{const d=copy(sample);d.vessels[0].name="a".repeat(200);assert.equal(validate(d),false)});
test("rejects corrupted backup",()=>assert.equal(validate({vessels:[],assets:[]}),false));
